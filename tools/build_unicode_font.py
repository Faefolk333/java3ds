"""Retain the original ASCII bitmap and add Unscii Latin/Greek/Cyrillic."""
from pathlib import Path
import re
r=Path(__file__).resolve().parents[1]
p=r/'java/javax/microedition/lcdui/BitmapFont.java'
ascii_glyphs=re.findall(r'0x([0-9a-fA-F]{16})L',p.read_text())[:128]
assert len(ascii_glyphs)==128
glyphs=[int(v,16) for v in ascii_glyphs]+[0]*(0x530-128)
for line in (r/'third-party/unscii/unicode-8x8.hex').read_text().splitlines():
 code,bitmap=line.split(':');code=int(code,16);assert 128<=code<len(glyphs) and len(bitmap)==16
 rows=[int(bitmap[i:i+2],16) for i in range(0,16,2)]
 glyphs[code]=sum(int(f'{row:08b}'[::-1],2)<<(8*i) for i,row in enumerate(rows))
for code in range(0x410,0x450):assert glyphs[code],hex(code)
p.write_text('package javax.microedition.lcdui;\n// ASCII: public-domain IBM font8x8. Extended: Unscii public-domain/CC0 subset.\n// Generated by tools/build_unicode_font.py; upstream notices in third-party.\nfinal class BitmapFont {static final long[] DATA={\n'+',\n'.join('0x%016xL'%v for v in glyphs)+'};}\n',encoding='utf-8',newline='\n')
print('UNICODE_FONT_BUILT',len(glyphs),'codepoint slots; complete Russian alphabet')
